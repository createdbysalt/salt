import "server-only";

/**
 * Known-Entity Gate (Captures V2 Phase 2 — Gate 2).
 *
 * Fast-tracks captures from known contacts:
 * - Watch expressions (Phase 3) — fastest path, indexed lookup
 * - Email matches a Person in Memory
 * - Domain matches an Organization in Memory
 *
 * If matched, the capture routes directly to that entity with high confidence.
 * This gate requires DB lookups but is still fast (indexed queries).
 */

import { createAdminClient } from "@/app/_lib/supabase/admin";
import {
  matchWatchExpressions,
  updateWatchMatchTimestamp,
  accumulateWatchSignals,
  type AccumulatedSignal,
} from "../watch-expressions";
import { queueReenrichment } from "../reenrichment-bridge";
import type { KnownEntityGateInput, GateResultSignal, AdmissionSignal } from "../../types/gate-result";
import { shouldGraduateWatch, buildRecordCaptureInput } from "../enrichment/record-capture-criteria";

/** Placeholder entity ID used for pending contacts that haven't graduated yet */
const PENDING_CONTACT_PLACEHOLDER = "00000000-0000-0000-0000-000000000000";

export interface KnownEntityGateInputExtended extends KnownEntityGateInput {
  /** Admission signals for graduation evaluation */
  admissionSignals?: AdmissionSignal[];
  admissionScore?: number;
}

export async function runKnownEntityGate(
  input: KnownEntityGateInputExtended
): Promise<GateResultSignal | null> {
  const { workspaceId, senderEmail, senderDomain, senderName } = input;

  if (!senderEmail && !senderDomain) {
    return null;
  }

  const watchMatches = await matchWatchExpressions(workspaceId, {
    emails: senderEmail ? [senderEmail] : undefined,
    domains: senderDomain ? [senderDomain] : undefined,
  });

  if (watchMatches.length > 0) {
    const match = watchMatches[0];
    const expression = match.expression;

    // Check if this is a pending contact watch
    if (
      expression.watchPurpose === "pending_contact" &&
      expression.targetEntityId === PENDING_CONTACT_PLACEHOLDER
    ) {
      // Accumulate new signals
      const newSignals: AccumulatedSignal[] = (input.admissionSignals ?? []).map((s) => ({
        type: s.type,
        weight: s.weight,
        evidence: s.evidence,
        captured_at: new Date().toISOString(),
      }));

      const updatedWatch = await accumulateWatchSignals(expression.id, newSignals);

      if (updatedWatch) {
        // Check if watch should graduate to CREATE
        const accumulatedAdmissionSignals: AdmissionSignal[] = updatedWatch.accumulatedSignals.map(
          (s) => ({
            type: s.type as AdmissionSignal["type"],
            weight: s.weight,
            evidence: s.evidence,
          })
        );

        const criteriaInput = buildRecordCaptureInput({
          admissionScore: input.admissionScore ?? 0,
          admissionSignals: input.admissionSignals ?? [],
          linkedRecords: [],
          senderClassification: "unknown",
          senderEmail,
          senderName,
        });

        const decision = shouldGraduateWatch(
          accumulatedAdmissionSignals,
          updatedWatch.captureCount,
          criteriaInput
        );

        if (decision.tier === "create") {
          // Watch graduates - return signal indicating record should be proposed
          // The actual proposal will be generated by the enrichment pipeline
          return {
            action: "signal",
            gate: "known-entity",
            target: {
              surface: "people", // Will be determined by proposal
              entityId: PENDING_CONTACT_PLACEHOLDER, // Signals this is a graduation
              matchType: expression.expressionType === "email" ? "email" : "domain",
              confidence: decision.confidence,
            },
            reason: `Pending contact graduated: ${decision.reason}`,
          };
        }
      }

      // Still pending, not ready to graduate
      return null;
    }

    // Regular entity watch - update timestamp and queue re-enrichment
    updateWatchMatchTimestamp(match.expression.id).catch(() => {});
    queueReenrichment(workspaceId, match);

    return {
      action: "signal",
      gate: "known-entity",
      target: {
        surface: match.expression.targetSurface,
        entityId: match.expression.targetEntityId,
        matchType: match.expression.expressionType === "email" ? "email" : "domain",
        confidence: match.expression.expressionType === "email" ? 95 : 85,
      },
      reason: `Watch expression match: ${match.expression.expressionType} = ${match.matchedValue}`,
    };
  }

  const admin = createAdminClient();

  if (senderEmail) {
    const emailLower = senderEmail.toLowerCase();
    const { data: personByEmail } = await admin
      .from("people")
      .select("id, display_name, emails")
      .eq("workspace_id", workspaceId)
      .contains("emails", [emailLower])
      .limit(1)
      .maybeSingle();

    if (personByEmail) {
      return {
        action: "signal",
        gate: "known-entity",
        target: {
          surface: "people",
          entityId: personByEmail.id,
          matchType: "email",
          confidence: 95,
        },
        reason: `Email matches known person: ${personByEmail.display_name ?? emailLower}`,
      };
    }

    const { data: personByBillingEmail } = await admin
      .from("people")
      .select("id, display_name, billing_email")
      .eq("workspace_id", workspaceId)
      .ilike("billing_email", emailLower)
      .limit(1)
      .maybeSingle();

    if (personByBillingEmail) {
      return {
        action: "signal",
        gate: "known-entity",
        target: {
          surface: "people",
          entityId: personByBillingEmail.id,
          matchType: "email",
          confidence: 90,
        },
        reason: `Billing email matches known person: ${personByBillingEmail.display_name ?? emailLower}`,
      };
    }
  }

  if (senderDomain) {
    const domainLower = senderDomain.toLowerCase();

    const { data: orgByDomain } = await admin
      .from("organizations")
      .select("id, display_name, domains")
      .eq("workspace_id", workspaceId)
      .contains("domains", [domainLower])
      .limit(1)
      .maybeSingle();

    if (orgByDomain) {
      return {
        action: "signal",
        gate: "known-entity",
        target: {
          surface: "organizations",
          entityId: orgByDomain.id,
          matchType: "domain",
          confidence: 85,
        },
        reason: `Domain matches known organization: ${orgByDomain.display_name ?? domainLower}`,
      };
    }

    const { data: orgByPrimaryDomain } = await admin
      .from("organizations")
      .select("id, display_name, domain")
      .eq("workspace_id", workspaceId)
      .ilike("domain", domainLower)
      .limit(1)
      .maybeSingle();

    if (orgByPrimaryDomain) {
      return {
        action: "signal",
        gate: "known-entity",
        target: {
          surface: "organizations",
          entityId: orgByPrimaryDomain.id,
          matchType: "domain",
          confidence: 85,
        },
        reason: `Primary domain matches known organization: ${orgByPrimaryDomain.display_name ?? domainLower}`,
      };
    }
  }

  return null;
}

/**
 * Check if we've had prior interaction with this sender.
 * Future: This will use watch expressions table.
 */
export async function checkPriorInteraction(
  workspaceId: string,
  senderEmail: string
): Promise<{ hasPriorInteraction: boolean; interactionType?: string }> {
  const admin = createAdminClient();
  const emailLower = senderEmail.toLowerCase();

  const { data: existingCapture } = await admin
    .from("capture_events")
    .select("id, source_type")
    .eq("workspace_id", workspaceId)
    .contains("extracted_data", { sender_email: emailLower })
    .limit(1)
    .maybeSingle();

  if (existingCapture) {
    return {
      hasPriorInteraction: true,
      interactionType: `Prior ${existingCapture.source_type} capture`,
    };
  }

  return { hasPriorInteraction: false };
}
