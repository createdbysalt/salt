/**
 * Overlapping stack of channel logos. Most-recent channel comes first (front).
 * Styled like the playbook app overlap — slightly smaller.
 */
export function ChannelLogoStack({
  channels,
  activeChannel,
  size = "sm",
}: {
  channels: Channel[];
  activeChannel?: Channel;
  size?: "xs" | "sm";
}) {
  // Active channel goes to the front
  const ordered = activeChannel
    ? [activeChannel, ...channels.filter((c) => c !== activeChannel)]
    : channels;

  const dim = size === "xs" ? "size-3" : "size-3.5";
  const wrapper = size === "xs" ? "size-6" : "size-7";
  const overlap = size === "xs" ? "-space-x-1" : "-space-x-1.5";

  return (
    <div className={cn("inline-flex items-center", overlap)}>
      {ordered.map((c) => (
        <span
          key={c}
          className={cn(
            wrapper,
            "inline-flex items-center justify-center rounded-full bg-card border border-border/60 shadow-sm ring-2 ring-card transition-transform hover:-translate-y-0.5 hover:z-10"
          )}
          title={c}
        >
          <ChannelLogo channel={c} className={dim} />
        </span>
      ))}
    </div>
  );
}
