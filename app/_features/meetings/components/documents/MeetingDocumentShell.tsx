"use client";

import { forwardRef } from "react";
import { format } from "date-fns";
import { cn } from "@repo/utils";

type MeetingDocumentShellProps = {
  title: string;
  meetingTitle: string;
  meetingDate: Date;
  meetingTime?: string;
  location?: string;
  children: React.ReactNode;
  className?: string;
};

export const MeetingDocumentShell = forwardRef<HTMLDivElement, MeetingDocumentShellProps>(
  function MeetingDocumentShell(
    { title, meetingTitle, meetingDate, meetingTime, location, children, className },
    ref,
  ) {
    return (
      <div
        ref={ref}
        className={cn(
          "mx-auto max-w-[800px] bg-white font-sans text-foreground print:max-w-none print:bg-white",
          className,
        )}
      >
        {/* Document header */}
        <header className="mb-8 border-b border-border/40 pb-6">
          <p className="mb-2 text-[10px] font-semibold uppercase tracking-[0.2em] text-muted-foreground">
            {title}
          </p>
          <h1 className="font-display text-2xl font-medium tracking-tight text-foreground">
            {meetingTitle}
          </h1>
          <div className="mt-3 flex flex-wrap items-center gap-x-4 gap-y-1 text-sm text-muted-foreground">
            <span>{format(meetingDate, "EEEE, MMMM d, yyyy")}</span>
            {meetingTime && (
              <>
                <span className="text-border">·</span>
                <span>{meetingTime}</span>
              </>
            )}
            {location && (
              <>
                <span className="text-border">·</span>
                <span>{location}</span>
              </>
            )}
          </div>
        </header>

        {/* Document content */}
        <div className="space-y-8">{children}</div>

        {/* Document footer */}
        <footer className="mt-12 border-t border-border/40 pt-4 print:mt-8">
          <p className="text-xs text-muted-foreground/60">
            Generated by Salt · {format(new Date(), "MMM d, yyyy 'at' h:mm a")}
          </p>
        </footer>
      </div>
    );
  },
);
