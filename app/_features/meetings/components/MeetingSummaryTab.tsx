"use client";

import { useState, useTransition } from "react";
import { FileText, Loader2, Plus, Sparkles, WandSparkles } from "lucide-react";
import { toast } from "sonner";
import { cn } from "@repo/utils";
import type { MeetingSummaryRecord } from "../queries";
import { addMeetingSummary } from "../actions";

type MeetingSummaryTabProps = {
  meetingId: string;
  summary?: MeetingSummaryRecord;
  description?: string;
  notes?: string;
};

export function MeetingSummaryTab({
  meetingId,
  summary,
  description,
  notes,
}: MeetingSummaryTabProps) {
  const [isEditing, setIsEditing] = useState(false);
  const [content, setContent] = useState("");
  const [isPending, startTransition] = useTransition();

  const handleSave = () => {
    if (!content.trim()) {
      toast.error("Summary cannot be empty");
      return;
    }

    startTransition(async () => {
      const result = await addMeetingSummary({
        meetingId,
        content: content.trim(),
        generatedBy: "manual",
      });

      if (!result.ok) {
        toast.error(result.message);
        return;
      }

      toast.success("Summary added");
      setIsEditing(false);
      setContent("");
    });
  };

  if (!summary && !description && !notes && !isEditing) {
    return (
      <div className="flex flex-col items-center justify-center py-12 text-center">
        <FileText className="mb-4 size-12 text-muted-foreground/40" strokeWidth={1.5} />
        <h3 className="text-lg font-medium text-foreground">No summary yet</h3>
        <p className="mt-1 max-w-xs text-sm text-muted-foreground">
          Add a summary manually or let Salt generate one from a transcript.
        </p>
        <div className="mt-6 flex items-center gap-2">
          <button
            type="button"
            onClick={() => setIsEditing(true)}
            className="inline-flex h-9 items-center gap-1.5 rounded-full border border-border/60 bg-card px-4 text-sm font-medium transition hover:bg-muted"
          >
            <Plus className="size-3.5" strokeWidth={2.5} />
            Add manually
          </button>
          <button
            type="button"
            onClick={() => toast("Upload a transcript first to enable AI summarization")}
            className="surface-aurora inline-flex h-9 items-center gap-1.5 rounded-full px-4 text-sm font-medium text-white"
          >
            <Sparkles className="size-3.5" strokeWidth={2.5} />
            Generate with Salt
          </button>
        </div>
      </div>
    );
  }

  if (isEditing) {
    return (
      <div className="space-y-4">
        <div className="flex items-center justify-between">
          <h3 className="flex items-center gap-2 text-sm font-medium text-foreground">
            <WandSparkles className="size-4" strokeWidth={2} />
            Add Summary
          </h3>
          <button
            type="button"
            onClick={() => {
              setIsEditing(false);
              setContent("");
            }}
            className="text-xs text-muted-foreground hover:text-foreground"
          >
            Cancel
          </button>
        </div>
        <textarea
          value={content}
          onChange={(e) => setContent(e.target.value)}
          placeholder="Enter a summary of this meeting..."
          className="min-h-[200px] w-full resize-none rounded-xl border border-border/60 bg-background px-4 py-3 text-sm focus:outline-none focus:ring-2 focus:ring-ring"
          autoFocus
        />
        <div className="flex justify-end">
          <button
            type="button"
            onClick={handleSave}
            disabled={isPending || !content.trim()}
            className="inline-flex h-9 items-center gap-1.5 rounded-full bg-foreground px-4 text-sm font-medium text-background transition hover:bg-foreground/90 disabled:opacity-60"
          >
            {isPending && <Loader2 className="size-3.5 animate-spin" />}
            Save summary
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      {summary && (
        <div className="space-y-2">
          <div className="flex items-center justify-between">
            <h3 className="flex items-center gap-2 text-sm font-medium text-foreground">
              <Sparkles className="size-4 text-flame" strokeWidth={2} />
              Summary
            </h3>
            <span className="text-xs text-muted-foreground">
              {summary.generatedBy === "manual" ? "Manual" : `Generated by ${summary.generatedBy}`}
            </span>
          </div>
          <p className="whitespace-pre-wrap text-sm leading-relaxed text-foreground/90">
            {summary.content}
          </p>
        </div>
      )}

      {description && (
        <div className="space-y-2">
          <h3 className="text-sm font-medium text-foreground">Description</h3>
          <p className="whitespace-pre-wrap text-sm leading-relaxed text-muted-foreground">
            {description}
          </p>
        </div>
      )}

      {notes && (
        <div className="space-y-2">
          <h3 className="text-sm font-medium text-foreground">Notes</h3>
          <p className="whitespace-pre-wrap text-sm leading-relaxed text-muted-foreground">
            {notes}
          </p>
        </div>
      )}

      {!summary && (
        <div className="border-t border-border/60 pt-4">
          <button
            type="button"
            onClick={() => setIsEditing(true)}
            className="inline-flex items-center gap-1.5 text-sm text-primary hover:underline"
          >
            <Plus className="size-3.5" />
            Add summary
          </button>
        </div>
      )}
    </div>
  );
}
