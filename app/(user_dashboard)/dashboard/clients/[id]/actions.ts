"use server";

import { createClient } from "@/app/_lib/supabase/server";
import { createAdminClient } from "@/app/_lib/supabase/admin";
import { getTenantContext } from "@/app/_lib/tenancy";
import { requireStudioMember } from "@/app/_lib/tenancy/guards";
import { revalidatePath } from "next/cache";
import { z } from "zod";
import { sendEmail } from "@/app/_lib/email/resend";
import { sendAccessRevokedEmail } from "@/app/_lib/email/bridge-emails";

const inviteSchema = z.object({
  email: z.string().email("Valid email required"),
  role: z.enum(["client", "viewer"]).default("client"),
});

/**
 * Invite a client user to access the Bridge portal
 * Creates auth user and client_users membership
 */
export async function inviteClientUser(clientId: string, formData: FormData) {
  try {
    const { context } = await getTenantContext();
    const studio = requireStudioMember(context);
    const supabase = await createClient();
    
    // Validate form data
    const rawData = {
      email: formData.get("email") as string,
      role: (formData.get("role") as string) || "client",
    };
    
    const validatedData = inviteSchema.parse(rawData);
    
    // Verify client belongs to this studio and get client name
    const { data: client } = await supabase
      .from("clients")
      .select("id, name")
      .eq("id", clientId)
      .eq("studio_id", studio.id)
      .single();
    
    if (!client) {
      return { error: "Invalid client" };
    }
    
    // Check if email is already a member of this client
    const { data: existingMember } = await supabase
      .from("client_users")
      .select("id, status")
      .eq("client_id", clientId)
      .eq("email", validatedData.email)
      .single();
    
    if (existingMember && existingMember.status === 'active') {
      return { error: "This email is already an active member of this client" };
    }
    
    const isRestoringAccess = !!existingMember; // True if they were previously a member (revoked/inactive)
    
    // Use Supabase Admin API to check/invite user
    const supabaseAdmin = createAdminClient();

    // Try to find existing user by listing all users and filtering by email
    const { data: allUsersData } = await supabaseAdmin.auth.admin.listUsers();
    const existingAuthUser = allUsersData?.users?.find(
      (u: any) => u.email?.toLowerCase() === validatedData.email.toLowerCase()
    );
    
    let userId: string;
    let emailSent = false;
    
    // Get the Bridge verification URL for magic link redirect
    // Magic links use URL fragments (#access_token=...) which are client-side only
    // We redirect to /bridge/verify where it exchanges the token, then redirects to /bridge
    const siteUrl = process.env.NEXT_PUBLIC_SITE_URL || 
                    (process.env.NODE_ENV === 'development' 
                      ? 'http://localhost:3000' 
                      : 'https://bridge.saltcore.io');
    const redirectUrl = `${siteUrl}/bridge/verify`;
    
    // Log the redirect URL for debugging
    console.log(`[inviteClientUser] Using magic link redirectUrl: ${redirectUrl} (env: ${process.env.NODE_ENV})`);
    
    if (existingAuthUser) {
      // User already exists in auth - send them a magic link via Supabase's OTP flow
      userId = existingAuthUser.id;
      console.log(`Re-adding existing user ${validatedData.email} to client ${clientId}`);
      
      try {
        // Use Supabase's signInWithOtp to send a magic link email
        // Redirects to /signin where AuthTokenHandler exchanges token & redirects to /bridge
        const { error: otpError } = await supabaseAdmin.auth.signInWithOtp({
          email: validatedData.email,
          options: {
            emailRedirectTo: redirectUrl,
            data: {
              client_id: clientId,
              role: validatedData.role,
            },
          },
        });
        
        if (otpError) {
          console.error("Error sending magic link:", otpError);
          // Don't fail the whole operation - they can still log in manually
        } else {
          emailSent = true;
          console.log(`Magic link sent to ${validatedData.email}`);
          
          // NOTE: We don't send a branded email here because:
          // 1. Supabase's OTP email contains the actual magic link with the token
          // 2. We can't replicate this link (it's generated by Supabase)
          // 3. Studio owners should style the Supabase email template instead
          // 4. Sending two emails with different links confuses users
        }
      } catch (emailError) {
        console.error("Error sending magic link:", emailError);
        // Don't fail - they can still access manually
      }
    } else {
      // New user - send invite email via Supabase auth
      // inviteUserByEmail uses code-based flow (not fragments), goes through /api/auth/callback
      const { data: authUser, error: inviteError } =
        await supabaseAdmin.auth.admin.inviteUserByEmail(
        validatedData.email,
        {
          data: {
            client_id: clientId,
            role: validatedData.role,
          },
          redirectTo: `${siteUrl}/api/auth/callback`,
        }
      );
      
      if (inviteError) {
        console.error("Error inviting user:", inviteError);
        return { error: inviteError.message || "Failed to send invite email" };
      }
      
      userId = authUser.user.id;
      emailSent = true;
      
      // NOTE: We don't send a branded invite email here because:
      // 1. Supabase's inviteUserByEmail sends its own email with the actual invite link
      // 2. We can't replicate this link (it's generated by Supabase with a unique code)
      // 3. Studio owners should customize the Supabase email template in the dashboard
      // 4. Future: We could send a "welcome" email AFTER they accept the invite
    }
    
    // Create or update client_users membership
    // Status: 'active' only if restoring a previously revoked member, otherwise 'pending'
    const membershipData = {
      client_id: clientId,
      studio_id: studio.id,
      user_id: userId,
      email: validatedData.email,
      role: validatedData.role,
      status: isRestoringAccess ? 'active' : 'pending',
    };
    
    const { error: membershipError } = isRestoringAccess
      ? await supabase
          .from("client_users")
          .update(membershipData)
          .eq("id", existingMember!.id)
      : await supabase
          .from("client_users")
          .insert(membershipData);
    
    if (membershipError) {
      console.error("Error creating client membership:", membershipError);
      if (membershipError.code === '23505') {
        return { error: "This user is already a member of this client" };
      }
      return { error: "Failed to add user to client" };
    }
    
    revalidatePath(`/dashboard/clients/${clientId}`);
    
    // Return appropriate success message based on whether it's a restore or new invite
    if (isRestoringAccess && emailSent) {
      return { 
        success: true, 
        message: "Access restored. Bridge link sent to the email." 
      };
    } else if (isRestoringAccess && !emailSent) {
      return { 
        success: true, 
        message: "Access restored. They can sign in to the bridge." 
      };
    } else if (emailSent) {
      return { 
        success: true, 
        message: "Invitation sent successfully." 
      };
    } else {
      return {
        success: true,
        message: "User invited. They can sign in to the bridge."
      };
    }
  } catch (error) {
    if (error instanceof z.ZodError) {
      return { error: error.errors[0].message };
    }
    console.error("Unexpected error:", error);
    return { error: "An unexpected error occurred" };
  }
}

/**
 * Revoke a client user's access
 */
export async function revokeClientUser(clientId: string, userId: string) {
  try {
    const { context } = await getTenantContext();
    const studio = requireStudioMember(context);
    const supabase = await createClient();
    
    // Verify client belongs to this studio and get details
    const { data: client } = await supabase
      .from("clients")
      .select("id, name")
      .eq("id", clientId)
      .eq("studio_id", studio.id)
      .single();
    
    if (!client) {
      return { error: "Invalid client" };
    }
    
    // Get client user email before deleting
    const { data: clientUser } = await supabase
      .from("client_users")
      .select("email")
      .eq("client_id", clientId)
      .eq("user_id", userId)
      .single();
    
    // Delete client_users membership
    const { error: deleteError } = await supabase
      .from("client_users")
      .delete()
      .eq("client_id", clientId)
      .eq("user_id", userId);
    
    if (deleteError) {
      console.error("Error revoking client user:", deleteError);
      return { error: "Failed to revoke access" };
    }
    
    // Send access revoked email
    if (clientUser?.email) {
      try {
        await sendAccessRevokedEmail({
          studioId: studio.id,
          clientName: client.name,
          clientUserEmail: clientUser.email,
        });
        console.log(`Access revoked email sent to ${clientUser.email}`);
      } catch (emailError) {
        console.error("Error sending revoke email:", emailError);
        // Don't fail the operation - access was already revoked
      }
    }
    
    revalidatePath(`/dashboard/clients/${clientId}`);
    return { success: true };
  } catch (error) {
    console.error("Unexpected error:", error);
    return { error: "An unexpected error occurred" };
  }
}

/**
 * Resend invite email to a client user.
 * Generates a fresh magic link and sends the welcome email again.
 */
export async function resendInvite(clientId: string, userId: string) {
  try {
    const { context } = await getTenantContext();
    const studio = requireStudioMember(context);
    const supabase = await createClient();
    const supabaseAdmin = createAdminClient();
    
    // Verify client belongs to this studio and get client name
    const { data: client } = await supabase
      .from("clients")
      .select("id, name")
      .eq("id", clientId)
      .eq("studio_id", studio.id)
      .single();
    
    if (!client) {
      return { error: "Invalid client" };
    }
    
    // Get client user details
    const { data: clientUser } = await supabase
      .from("client_users")
      .select("email, role")
      .eq("client_id", clientId)
      .eq("user_id", userId)
      .single();
    
    if (!clientUser) {
      return { error: "Client user not found" };
    }
    
    // Get the Bridge verification URL for magic link redirect
    // Magic links use URL fragments (#access_token=...) which are client-side only
    // We redirect to /bridge/verify where it exchanges the token, then redirects to /bridge
    const siteUrl = process.env.NEXT_PUBLIC_SITE_URL || 
                    (process.env.NODE_ENV === 'development' 
                      ? 'http://localhost:3000' 
                      : 'https://bridge.saltcore.io');
    const redirectUrl = `${siteUrl}/bridge/verify`;
    
    // Log the redirect URL for debugging
    console.log(`[resendInvite] Using magic link redirectUrl: ${redirectUrl} (env: ${process.env.NODE_ENV})`);
    
    // Send magic link using Supabase's built-in OTP flow
    const { error: otpError } = await supabaseAdmin.auth.signInWithOtp({
      email: clientUser.email,
      options: {
        emailRedirectTo: redirectUrl,
        data: {
          client_id: clientId,
          role: clientUser.role,
        },
      },
    });
    
    if (otpError) {
      console.error("Error sending magic link:", otpError);
      return { error: "Failed to send invite link" };
    }
    
    console.log(`Magic link resent to ${clientUser.email}`);
    
    // NOTE: We don't send a branded resend email here because:
    // 1. Supabase's OTP email contains the actual magic link
    // 2. Studio owners should customize the Supabase email template
    // 3. Sending two emails with different links confuses users
    
    revalidatePath(`/dashboard/clients/${clientId}`);
    return { success: true, message: "Invite resent successfully" };
  } catch (error) {
    console.error("Unexpected error:", error);
    return { error: "An unexpected error occurred" };
  }
}

