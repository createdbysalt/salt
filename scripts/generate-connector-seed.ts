/**
 * Generate the connector-platform seed migration FROM the existing
 * hand-maintained structures (connector-platform plan Phase 2.3).
 *
 * Nothing is retyped: catalog entries come from CONNECTOR_CATALOG,
 * auth config pins + API-key wiring from providers.ts, risk
 * classifications from the tool policy registry, Ask Salt exposure
 * from the connector manifest.
 *
 * Usage: pnpm tsx scripts/generate-connector-seed.ts > supabase/migrations/<ts>_seed_connector_platform.sql
 *
 * Run WITHOUT Composio env vars so toComposioAuthConfigId returns the
 * pinned repo defaults, not a per-environment override.
 */
import { CONNECTOR_CATALOG } from "../app/_features/connectors/connector-catalog";
import {
  COMPOSIO_WORKSPACE_PROVIDERS,
  isComposioApiKeyProvider,
  toComposioApiKeyField,
  toComposioAppName,
  toComposioAuthConfigId,
  type ComposioWorkspaceProvider,
} from "../app/_lib/composio/providers";
import { COMPOSIO_TOOL_SLUGS } from "../app/_lib/composio/tool-slugs";
import { getComposioToolPolicy } from "../app/_lib/composio/tool-policy-registry";
import { ASK_SALT_CONNECTOR_MANIFEST } from "../app/_lib/composio/connector-manifest";

function q(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function qOrNull(value: string | null | undefined): string {
  return value == null || value === "" ? "NULL" : q(value);
}

function jsonb(value: unknown): string {
  return `${q(JSON.stringify(value))}::jsonb`;
}

const guardEnvVars = Object.keys(process.env).filter(
  (key) => key.startsWith("COMPOSIO_") && key.endsWith("_AUTH_CONFIG_ID"),
);
if (guardEnvVars.length > 0) {
  console.error(
    `Refusing to generate: env overrides present (${guardEnvVars.join(", ")}). ` +
      "Run without Composio auth-config env vars so pinned defaults are captured.",
  );
  process.exit(1);
}

const lines: string[] = [];

lines.push(`-- ============================================================================
-- SEED CONNECTOR PLATFORM (connector-platform plan Phase 2.3)
-- ============================================================================
--
-- GENERATED by scripts/generate-connector-seed.ts from the hand-maintained
-- structures (CONNECTOR_CATALOG, providers.ts, tool-policy-registry.ts,
-- connector-manifest.ts). Do not hand-edit rows here — regenerate, or use
-- the review queue / sync job once live.
--
-- Idempotent: ON CONFLICT DO NOTHING so a re-run never clobbers rows the
-- sync job or review queue has since updated.
-- ============================================================================
`);

// ── connector_catalog ────────────────────────────────────────────────────────
lines.push("-- connector_catalog (from CONNECTOR_CATALOG + providers.ts)");
const catalogByProvider = new Map(
  CONNECTOR_CATALOG.filter((entry) => entry.ownership === "composio").map(
    (entry) => [entry.providerKey, entry] as const,
  ),
);

for (const provider of COMPOSIO_WORKSPACE_PROVIDERS) {
  const entry = catalogByProvider.get(provider);
  const toolkit = toComposioAppName(provider);
  const authConfigId = toComposioAuthConfigId(provider);
  const comingSoon = entry?.comingSoon ?? authConfigId === "";
  const authMethod = isComposioApiKeyProvider(provider) ? "api_key" : "oauth";
  lines.push(
    `INSERT INTO public.connector_catalog (provider_key, toolkit_slug, name, description, category, auth_method, coming_soon, meta)
VALUES (${q(provider)}, ${q(toolkit)}, ${q(entry?.name ?? provider)}, ${q(entry?.description ?? "")}, ${q(entry?.category ?? "productivity")}, ${q(authMethod)}, ${comingSoon}, ${jsonb({ catalogId: entry?.id ?? null, phase: entry?.phase ?? null, showInCatalog: entry?.showInCatalog ?? false, connectHelp: entry?.connectHelp ?? null, nativeBadge: entry?.nativeBadge ?? null, seededFrom: "connector-catalog.ts" })})
ON CONFLICT (provider_key) DO NOTHING;`,
  );
}

// ── connector_overrides ──────────────────────────────────────────────────────
lines.push("\n-- connector_overrides (auth config pins from providers.ts; Ask Salt exposure from the manifest)");
const manifestByToolkit = new Map(
  ASK_SALT_CONNECTOR_MANIFEST.map((entry) => [entry.toolkit, entry] as const),
);

for (const provider of COMPOSIO_WORKSPACE_PROVIDERS) {
  const entry = catalogByProvider.get(provider);
  const authConfigId = toComposioAuthConfigId(provider);
  const manifest = manifestByToolkit.get(provider);
  const tier = manifest ? "action" : "catalog_only";
  const apiKeyField = isComposioApiKeyProvider(provider)
    ? toComposioApiKeyField(provider)
    : null;
  const envVar = `COMPOSIO_${provider.toUpperCase()}_AUTH_CONFIG_ID`;
  const apiKeyForm = entry && "apiKeyForm" in entry ? entry.apiKeyForm : undefined;
  lines.push(
    `INSERT INTO public.connector_overrides (provider_key, tier, auth_config_id, auth_config_env_var, api_key_field_name, api_key_form, ask_salt_slug_prefix, ask_salt_label)
VALUES (${q(provider)}, ${q(tier)}, ${q(authConfigId)}, ${q(envVar)}, ${qOrNull(apiKeyField)}, ${apiKeyForm ? jsonb(apiKeyForm) : "NULL"}, ${qOrNull(manifest?.slugPrefix)}, ${qOrNull(manifest?.label)})
ON CONFLICT (provider_key) DO NOTHING;`,
  );
}

// ── tool_classifications ─────────────────────────────────────────────────────
lines.push(
  "\n-- tool_classifications (from tool-policy-registry.ts; status approved, source seed)",
);
const slugs = [...new Set(Object.values(COMPOSIO_TOOL_SLUGS))];
let classified = 0;
for (const slug of slugs) {
  const policy = getComposioToolPolicy(slug);
  if (!policy) continue;
  classified += 1;
  lines.push(
    `INSERT INTO public.tool_classifications (tool_slug, risk, requires_human_confirmation, status, source, approved_at, notes)
VALUES (${q(slug)}, ${q(policy.risk)}, ${policy.requiresHumanConfirmation}, 'approved', 'seed', now(), 'Seeded from hand-curated TOOL_POLICIES (audited 2026-06-11)')
ON CONFLICT (tool_slug) DO NOTHING;`,
  );
}

lines.push(
  `\n-- ${catalogByProvider.size} catalog entries / ${COMPOSIO_WORKSPACE_PROVIDERS.length} providers / ${classified} tool classifications`,
);

process.stdout.write(lines.join("\n") + "\n");
